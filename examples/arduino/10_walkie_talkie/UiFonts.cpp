const UiGlyph *findMontserrat20Glyph(char ch) {
  for (size_t i = 0; i < sizeof(kMontserrat20Glyphs) / sizeof(kMontserrat20Glyphs[0]); i++) {
    if (kMontserrat20Glyphs[i].ch == ch) {
      return &kMontserrat20Glyphs[i];
    }
  }
  return nullptr;
}

const UiPackedGlyph *findUnscii8Glyph(char ch) {
  uint8_t code = (uint8_t)ch;
  if (code < 32 || code > 127) {
    return nullptr;
  }
  return &kUnscii8Glyphs[code - 31];
}

bool readUnscii8GlyphPixel(const UiPackedGlyph *glyph, uint8_t col, uint8_t row) {
  if (!glyph || col >= glyph->width || row >= glyph->height) {
    return false;
  }
  uint16_t bitIndex = glyph->bitmapIndex * 8 + row * glyph->width + col;
  uint8_t packed = pgm_read_byte(&kUnscii8Bitmap[bitIndex / 8]);
  return (packed & (0x80 >> (bitIndex & 0x07))) != 0;
}

uint16_t measureUnscii8Text(const char *text) {
  if (!text) {
    return 0;
  }
  uint16_t width = 0;
  for (const char *p = text; *p; p++) {
    const UiPackedGlyph *glyph = findUnscii8Glyph(*p);
    width += glyph ? glyph->advance : 8;
  }
  return width;
}
